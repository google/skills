// Generated by litert-google-tensor (scripts/package_ai_pack.py) for the AI
// pack "{{PACK_NAME}}". On the Pixel SoCs that have a Google Tensor build in
// the pack ({{SOC_LIST_TEXT}}) it runs "{{MODEL_NAME}}" on the TPU; everywhere
// else - or if the TPU path fails - it runs the original model on the CPU.
//
// Usage (from a coroutine, off the main thread):
//
//   val loaded = TensorModelLoader.load(context)  // keep it while you need it
//   val inputs = loaded.model.createInputBuffers()
//   val outputs = loaded.model.createOutputBuffers()
//   inputs[0].writeFloat(myInput)                 // your pre-processing
//   loaded.model.run(inputs, outputs)
//   val result = outputs[0].readFloat()           // your post-processing
//   // When done: close the buffers, then loaded.close().
//
// Every load() logs one line, tag "LiteRtTensor", starting with
// "LITERT_TENSOR_RESULT " and followed by JSON: {"path":"npu"|"cpu", ...}.
// See INTEGRATION.md next to the generated AI pack.
package {{KOTLIN_PACKAGE}}

import android.content.Context
import android.os.Build
import android.os.SystemClock
import android.util.Log
import com.google.ai.edge.litert.Accelerator
import com.google.ai.edge.litert.BuiltinNpuAcceleratorProvider
import com.google.ai.edge.litert.CompiledModel
import com.google.ai.edge.litert.Environment
import com.google.ai.edge.litert.ModelProvider
import com.google.ai.edge.litert.ModelSelector
import com.google.ai.edge.litert.NpuCompatibilityChecker
import com.google.ai.edge.litert.deployment.AiPackModelProvider
import java.io.IOException
import kotlin.coroutines.cancellation.CancellationException
import org.json.JSONObject

object TensorModelLoader {
  /** Name of the AI pack (its directory and `aiPack.packName`). */
  const val AI_PACK_NAME = "{{PACK_NAME}}"

  /** The model inside the AI pack, without the `#group_...` suffix. */
  const val PACK_MODEL_PATH = "model/{{MODEL_NAME}}.tflite"

  /** The original (uncompiled) model in the app's base assets: the CPU path. */
  const val CPU_MODEL_ASSET = "litert/{{MODEL_NAME}}_cpu_gpu.tflite"

  /** `aiPack.dynamicDelivery.deliveryType` of the AI pack. */
  const val DELIVERY = "{{DELIVERY}}"

  /** `Build.SOC_MODEL` values that have a Google Tensor build in the pack. */
  val PACKAGED_SOC_MODELS: Set<String> = setOf({{SOC_MODELS_KOTLIN}})

  const val LOG_TAG = "LiteRtTensor"
  const val RESULT_PREFIX = "LITERT_TENSOR_RESULT "

  /** Which model [load] returned. */
  enum class Path {
    /** The Google Tensor build from the AI pack, on the TPU. */
    NPU,
    /** The original model from the base assets, on the CPU. */
    CPU,
  }

  /** A loaded model. Close it (after its tensor buffers) when done. */
  class Loaded
  internal constructor(
    val model: CompiledModel,
    val path: Path,
    val loadMs: Long,
    /** Why the TPU path was not used, or null. */
    val npuError: String?,
    private val environment: Environment?,
  ) : AutoCloseable {
    override fun close() {
      model.close()
      environment?.close()
    }
  }

  /**
   * True on devices that should run the Google Tensor build: LiteRT's own
   * Google Tensor check (Android version and build) plus an SoC that has a
   * build in the pack.
   */
  fun isPackagedTensorDevice(): Boolean =
    NpuCompatibilityChecker.GoogleTensor.isDeviceSupported() &&
      Build.SOC_MODEL.trim() in PACKAGED_SOC_MODELS

  /** Loads the Google Tensor build on the TPU if possible, else the CPU model. */
  suspend fun load(context: Context): Loaded {
    val start = SystemClock.elapsedRealtime()
    var npuError: String? = null
    if (isPackagedTensorDevice()) {
      var environment: Environment? = null
      try {
        environment =
          Environment.create(
            BuiltinNpuAcceleratorProvider(context, NpuCompatibilityChecker.GoogleTensor)
          )
        val model = loadTensorBuild(context, environment)
        val elapsed = SystemClock.elapsedRealtime() - start
        return report(Loaded(model, Path.NPU, elapsed, null, environment))
      } catch (e: CancellationException) {
        environment?.close()
        throw e
      } catch (e: Exception) {
        environment?.close()
        npuError = "${e.javaClass.simpleName}: ${e.message}"
        Log.w(LOG_TAG, "Google Tensor TPU path failed; using the CPU model.", e)
      }
    } else {
      npuError = "not a packaged Google Tensor device (SoC: ${Build.SOC_MODEL})"
    }
    val model =
      CompiledModel.create(context.assets, CPU_MODEL_ASSET, CompiledModel.Options(Accelerator.CPU))
    val elapsed = SystemClock.elapsedRealtime() - start
    return report(Loaded(model, Path.CPU, elapsed, npuError, null))
  }

  private suspend fun loadTensorBuild(context: Context, environment: Environment): CompiledModel {
    val provider: ModelProvider =
      if (DELIVERY == "install-time" || isAppAsset(context, PACK_MODEL_PATH)) {
        // An install-time AI pack, or a debug build that carries the model
        // itself (the optional quick test in INTEGRATION.md).
        ModelProvider.staticModel(ModelProvider.Type.ASSET, PACK_MODEL_PATH, Accelerator.NPU)
      } else {
        // fast-follow / on-demand: downloads the pack if it is not on the device yet.
        AiPackModelProvider(context, AI_PACK_NAME, PACK_MODEL_PATH, Accelerator.NPU)
      }
    // Throws IllegalStateException if the NPU is unavailable or the download fails.
    val selected = ModelSelector(provider).selectModel(environment)
    val options = CompiledModel.Options(Accelerator.NPU)
    return if (selected.getType() == ModelProvider.Type.ASSET) {
      // Install-time AI pack assets: read them through a fresh package context.
      val assets = context.createPackageContext(context.packageName, 0).assets
      CompiledModel.create(assets, selected.getPath(), options, environment)
    } else {
      CompiledModel.create(selected.getPath(), options, environment)
    }
  }

  /** True if the app's own APK assets contain [path]. */
  private fun isAppAsset(context: Context, path: String): Boolean =
    try {
      context.assets.open(path).close()
      true
    } catch (e: IOException) {
      false
    }

  private fun report(loaded: Loaded): Loaded {
    val result =
      JSONObject()
        .put("path", loaded.path.name.lowercase())
        .put("soc", Build.SOC_MODEL)
        .put("sdk", Build.VERSION.SDK_INT)
        .put("build_id", Build.ID)
        .put("pack", AI_PACK_NAME)
        .put("delivery", DELIVERY)
        .put("load_ms", loaded.loadMs)
        .put("npu_error", loaded.npuError ?: JSONObject.NULL)
    Log.i(LOG_TAG, RESULT_PREFIX + result)
    return loaded
  }
}
